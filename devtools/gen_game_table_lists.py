#!/usr/bin/env python3
"""Write the two lists the run-time table loader (platform/game_tables.cpp) compiles in: names, addresses, counts, hashes
and offsets only, never a byte of the game's tables. Run it by hand when include/AdvisorScoring.h renames a scorer, when
devtools/gen_game_tables.py changes its lists, or to add a build of the program; the build never runs it.

usage: python3 -I devtools/gen_game_table_lists.py [--program NAME=FILE ...]

  include/platform/game_table_lists.inc   the blocks the loader finds (devtools/gen_game_tables.py's PARTS, WINDOW_SCRIPTS and
                                          WINDOW_HASHES), the 241 scorers in the order of their 2.04b3 addresses (the order a
                                          program's scorer functions are ranked in), and the known builds: the SHA-1 of each
                                          program's data fork with the offset of every block from its 2.04b3 address, so that
                                          a known program is read without the content search
  include/platform/game_table_zeros.inc   each window script's macro as that many zero words: the arrays' size when the tables
                                          are read at run time (src/game/ui keeps its definitions as they are)

--program NAME=FILE: a full Mac program (its data fork) to list as a known build named NAME; the offsets are the ones
devtools/gen_game_tables.py's content search finds in it. Without any, the builds already listed are kept as they are.
"""
import argparse
import hashlib
import importlib.util
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
MONO = HERE.parent
LISTS = MONO / "include" / "platform" / "game_table_lists.inc"
ZEROS = MONO / "include" / "platform" / "game_table_zeros.inc"
HEADER = MONO / "include" / "AdvisorScoring.h"

spec = importlib.util.spec_from_file_location("gen_game_tables", HERE / "gen_game_tables.py")
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)


def scorers():
    names = {}
    for line in HEADER.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*u?int32_t\s+(_ADVISOR_\w+)\(\);\s*//\s*(0x[0-9a-fA-F]{8})", line)
        if m:
            address = int(m.group(2), 16)
            assert names.get(address, m.group(1)) == m.group(1), "two scorers at 0x%08x" % address
            names[address] = m.group(1)
    return sorted(names.items())


def build_offsets(path):
    """(SHA-1 of the file, its size, [offset of each part], [offset of each window script]) from the content search."""
    data = pathlib.Path(path).read_bytes()
    view = g.BuildView(g.Program(path), HEADER)
    g.generate(path)                      # the seven outputs must have the known SHA-1s, or the build is not listed

    def offset(lo, length):
        return next(d for a, b, d in view.regions if a == lo and b == lo + length)

    parts = [offset(addr, length) for _, addr, length, _, _ in g.PARTS]
    scripts = [offset(addr, 2 * words) for addr, words, _ in g.WINDOW_SCRIPTS]
    return hashlib.sha1(data).hexdigest(), len(data), parts, scripts


def old_builds():
    """The builds the list holds now: [(name, sha1, size, parts, scripts)]."""
    out = []
    if LISTS.exists():
        for m in re.finditer(r'^TPW_GAME_TABLE_BUILD\("([^"]+)", "([0-9a-f]{40})", (\d+), \(([^)]*)\), \(([^)]*)\)\)$',
                             LISTS.read_text(), re.M):
            nums = [[int(x, 0) for x in grp.split(",")] for grp in (m.group(4), m.group(5))]
            out.append((m.group(1), m.group(2), int(m.group(3)), nums[0], nums[1]))
    return out


def signed(v):
    return "-0x%X" % -v if v < 0 else "0x%X" % v


def write(path, lines):
    text = "\n".join(lines) + "\n"
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
        print("wrote", path.relative_to(MONO))
    else:
        print("unchanged", path.relative_to(MONO))


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--program", action="append", default=[], metavar="NAME=FILE")
    a = ap.parse_args(argv)
    builds = old_builds()
    for item in a.program:
        name, _, path = item.partition("=")
        sha1, size, parts, scripts = build_offsets(path)
        builds = [b for b in builds if b[1] != sha1] + [(name, sha1, size, parts, scripts)]
    by_hash = {s: (anchor, whole, ordinal, copies) for s, (anchor, whole, ordinal, copies) in g.WINDOW_HASHES.items()}
    assert [s for s, _, _ in g.WINDOW_SCRIPTS] == list(g.WINDOW_HASHES), "WINDOW_SCRIPTS and WINDOW_HASHES list other scripts"
    lines = [
        "// The run-time table loader's lists (platform/game_tables.cpp): names, addresses, counts, hashes and offsets only.",
        "// Generated by devtools/gen_game_table_lists.py from devtools/gen_game_tables.py and include/AdvisorScoring.h; rerun it",
        "// rather than editing this file. Each section is there when the includer defines its macro.",
        "",
        "// The blocks of the tables without pointers, as the 2.04b3 build holds them: (id, address, bytes, SHA-1 of the first 32",
        "// bytes, SHA-1 of all of them). The content search finds each once in a program.",
        "#ifdef TPW_GAME_TABLE_PART",
    ]
    for (name, addr, length, anchor, whole), ident in zip(g.PARTS, ("LegalTexts", "AdvisorLines", "MessageTable", "BalanceRows",
                                                                     "RideTemplates")):
        lines.append('TPW_GAME_TABLE_PART(%s, 0x%08X, %d, "%s", "%s")' % (ident, addr, length, anchor, whole))
    lines += [
        "#endif",
        "",
        "// The window scripts: (2.04b3 address without 0x, words, the array src/game/ui defines, SHA-1 of the first 32 bytes, SHA-1",
        "// of the script, its place among the identical copies by address, the number of identical copies in the 2.04b3 build).",
        "#ifdef TPW_GAME_TABLE_WINDOW_SCRIPT",
    ]
    for addr, words, array in g.WINDOW_SCRIPTS:
        anchor, whole, ordinal, copies = by_hash[addr]
        lines.append('TPW_GAME_TABLE_WINDOW_SCRIPT(%08X, %d, %s, "%s", "%s", %d, %d)'
                     % (addr, words, array, anchor, whole, ordinal, copies))
    lines += [
        "#endif",
        "",
        "// The scorers, CAdvisorScoring's _ADVISOR_* members: (2.04b3 code address, name), in the order of the addresses. A",
        "// program's scorer functions lie in this order in every build, so the k-th lowest code address is the k-th entry.",
        "#ifdef TPW_GAME_TABLE_SCORER",
    ]
    for address, name in scorers():
        lines.append("TPW_GAME_TABLE_SCORER(0x%08X, %s)" % (address, name))
    lines += [
        "#endif",
        "",
        "// The known builds: (name, SHA-1 of the program's data fork, its size, (the offset of each part from its 2.04b3 address,",
        "// in the order above), (the offset of each window script, in the order above)).",
        "#ifdef TPW_GAME_TABLE_BUILD",
    ]
    for name, sha1, size, parts, scripts in builds:
        lines.append('TPW_GAME_TABLE_BUILD("%s", "%s", %d, (%s), (%s))'
                     % (name, sha1, size, ", ".join(signed(v) for v in parts), ", ".join(signed(v) for v in scripts)))
    lines.append("#endif")
    write(LISTS, lines)

    zeros = [
        "// Each window script's macro as that many zero words, the arrays' size when the tables are read at run time (the",
        "// tables-off WindowScripts.inc the build writes includes this file; platform/game_tables.cpp fills the arrays).",
        "// Generated by devtools/gen_game_table_lists.py from devtools/gen_game_tables.py's WINDOW_SCRIPTS; counts only.",
        "#pragma once",
        "",
        "#define TPW_ZEROS_1 0",
    ]
    top = max(w for _, w, _ in g.WINDOW_SCRIPTS).bit_length() - 1
    for k in range(1, top + 1):
        zeros.append("#define TPW_ZEROS_%d TPW_ZEROS_%d, TPW_ZEROS_%d" % (1 << k, 1 << (k - 1), 1 << (k - 1)))
    zeros.append("")
    for addr, words, array in g.WINDOW_SCRIPTS:
        bits = ["TPW_ZEROS_%d" % (1 << k) for k in range(top, -1, -1) if words & (1 << k)]
        zeros.append("#define TPW_WINDOW_SCRIPT_%08X %s   // %s, %d words" % (addr, ", ".join(bits), array, words))
    write(ZEROS, zeros)


if __name__ == "__main__":
    main(sys.argv[1:])
