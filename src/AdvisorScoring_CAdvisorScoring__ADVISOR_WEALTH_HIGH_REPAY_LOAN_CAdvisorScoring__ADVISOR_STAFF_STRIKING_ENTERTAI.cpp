namespace {
// lwz r3, off(r3): the word at the Mac offset from this (unaligned-safe).
int32_t WordAt(const void* self, size_t off) {
    int32_t v;
    std::memcpy(&v, static_cast<const char*>(self) + off, 4);
    return v;
}
}  // namespace

